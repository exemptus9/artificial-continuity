VERSION = '1.0.0'
MESSAGE = 'ContinuityMessengerMessage/1'
REPORT = 'ContinuityMessengerImport/1'
ORIGINAL = 'ContinuityMessengerOriginal/1'
MAX_INPUT = 64_000_000
MAX_MESSAGES = 100_000
VOID = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr'}


class Node:
    def __init__(self, tag='', attrs=()):
        self.tag, self.attrs, self.children = tag, dict(attrs), []

    def has_class(self, cls):
        return cls in self.attrs.get('class', '').split()

    def find(self, cls):
        return next((n for n in self.walk() if n.has_class(cls)), None)

    def walk(self):
        yield self
        for item in self.children:
            if isinstance(item, Node):
                yield from item.walk()


class Tree(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node(); self.stack = [self.root]; self.repairs = 0

    def handle_starttag(self, tag, attrs):
        node = Node(tag, attrs); self.stack[-1].children.append(node)
        if tag not in VOID:
            self.stack.append(node)

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in VOID:
            self.handle_endtag(tag)

    def handle_endtag(self, tag):
        for i in range(len(self.stack) - 1, 0, -1):
            if self.stack[i].tag == tag:
                self.repairs += len(self.stack) - i - 1
                self.stack = self.stack[:i]
                return
        self.repairs += 1

    def handle_data(self, data):
        self.stack[-1].children.append(data)


def text(node):
    """Decoded text projection; line breaks and literal spaces are not stripped.

    Non-visible active content is excluded from this derivative, but survives
    byte-for-byte in the original. BR is LF; adjacent block children are LF.
    """
    if node is None:
        return ''
    if isinstance(node, str):
        return node
    if node.tag in {'script', 'style', 'template', 'noscript'}:
        return ''
    if node.tag == 'br':
        return '\n'
    parts = []
    previous_block = False
    for child in node.children:
        value = text(child)
        block = isinstance(child, Node) and child.tag in {'div', 'p', 'li', 'blockquote', 'pre'}
        if value and parts and (block or previous_block) and not parts[-1].endswith('\n') and not value.startswith('\n'):
            parts.append('\n')
        if value:
            parts.append(value)
            previous_block = block
    return ''.join(parts)


def flags(sender, body, self_senders, previews=False):
    lower = body.casefold()
    bot = sender.casefold() in {'meta ai', 'chatgpt', 'assistant', 'facebook ai'}
    values = []
    if bot:
        values.append('platform_ai_sender')
    if any(v in lower for v in ('as an ai', 'as a language model', 'chatgpt', 'meta ai', 'openai', 'view other drafts')) or re.search(r'\bword\b.{0,120}\bis not a real word\b', lower):
        values.append('possible_copied_or_discussed_ai')
    if lower.startswith('messages are generated by ai.'):
        values.append('platform_ai_disclaimer')
    if re.search(r'(?im)^\s*(?:forwarded|quoted|>\s)', body):
        values.append('possible_quote_or_forward')
    if previews:
        values.append('separate_link_preview_preserved')
    if not body.strip():
        values.append('empty_or_media_only')
    if any(v in body for v in ('Ã', 'â€', 'ðŸ')):
        values.append('possible_mojibake_not_repaired')
    authorship = 'PLATFORM_GENERATED' if 'platform_ai_disclaimer' in values else 'AI_GENERATED' if bot else 'unverified_self_attributed' if sender in self_senders else 'third_party_unverified'
    return authorship, values


def html_date(value):
    try:
        return datetime.strptime(value, '%b %d, %Y %I:%M:%S%p').isoformat()
    except ValueError:
        return None


def base_message(source_hash, ordinal, title, sender, body, self_senders):
    # File+occurrence identity preserves repeated identical messages and separate
    # witnesses. A re-export is a separate witness; no cross-export merge guessed.
    authorship, contamination = flags(sender, body, self_senders)
    return {'format': MESSAGE, 'adapter_version': VERSION,
            'id': 'MESSENGER.MSG.' + C.digest([source_hash, ordinal]),
            'source_file_sha256': source_hash, 'source_ordinal': ordinal,
            'conversation_id': 'MESSENGER.THREAD.' + source_hash,
            'thread_title': title, 'sender': sender,
            'attribution_basis': 'sender label in supplied export; account identity and composition unverified',
            'body': body, 'body_sha256': G.raw_hash(body.encode('utf-8')),
            'normalized_search_text': ' '.join(body.split()),
            'links': [], 'attachments': [], 'reactions': [], 'reply_to': None,
            'timestamp_original': None, 'datetime_local_unspecified_zone': None,
            'observed_at': None, 'timezone_provenance': 'not-recorded',
            'classification': 'platform_system_event' if 'platform_ai_disclaimer' in contamination else 'message', 'authorship': authorship,
            'contamination_flags': contamination, 'style_eligible': False,
            'authorship_review': 'unreviewed', 'privacy': 'PRIVATE_VAULT',
            'publication_approved': False, 'evidence_class': 'EXACT_SOURCE',
            'evidence_scope': 'Decoded projection of supplied historical export, not truth of the statement or exact original bytes',
            'link_previews': [], 'warnings': []}


def parse_html(raw, source_hash, self_senders):
    encoding = 'utf-8-sig'
    try:
        decoded = raw.decode(encoding)
    except UnicodeDecodeError:
        declared = re.search(br'charset\s*=\s*["\x27]?([A-Za-z0-9_-]+)', raw[:8192], re.I)
        if not declared:
            raise C.ContextError('HTML encoding is invalid/unknown; raw file retained at its source, no guessed decoding.')
        encoding = declared.group(1).decode('ascii')
        try:
            decoded = raw.decode(encoding)
        except (LookupError, UnicodeError) as exc:
            raise C.ContextError('Declared HTML encoding cannot decode the original.') from exc
    parser = Tree(); parser.feed(decoded); parser.close()
    title_node = next((n for n in parser.root.walk() if n.tag == 'title'), None)
    title = text(title_node) or text(parser.root.find('_a70e')) or 'Untitled supplied Messenger thread'
    messages, metadata = [], []
    blocks = [n for n in parser.root.walk() if n.has_class('_a6-g')]
    if not blocks or len(blocks) > MAX_MESSAGES:
        raise C.ContextError('Unsupported HTML: expected bounded Messenger _a6-g message blocks.')
    for ordinal, block in enumerate(blocks, 1):
        sender_node, date_node, content = block.find('_a6-h'), block.find('_a72d'), block.find('_a6-p')
        if sender_node is None or date_node is None:
            metadata.append({'source_ordinal': ordinal, 'classification': 'archive_metadata', 'decoded_text': text(block)})
            continue
        sender, date = text(sender_node), text(date_node)
        # Current Meta HTML layout: outer content DIV contains [system marker,
        # authored body, preview/attachments, reactions]. Previews stay separate.
        wrappers = [n for n in content.children if isinstance(n, Node)] if content else []
        sections = [n for n in wrappers[0].children if isinstance(n, Node)] if len(wrappers) == 1 else []
        fallback = len(sections) < 2
        body_node = sections[1] if not fallback else content
        body = text(body_node)
        message = base_message(source_hash, ordinal, title, sender, body, self_senders)
        message['timestamp_original'] = date
        message['datetime_local_unspecified_zone'] = html_date(date)
        if message['datetime_local_unspecified_zone'] is None:
            message['warnings'].append('unparsed_timestamp_preserved_verbatim')
        if fallback:
            message['warnings'].append('unrecognized_content_layout_full_text_projection')
        if content:
            for node in content.walk():
                if node.tag == 'a' and node.attrs.get('href'):
                    uri = node.attrs['href']
                    message['links'].append(uri)
                    if ('download' in node.attrs or not re.match(r'^[A-Za-z][A-Za-z0-9+.-]*:', uri) and not uri.startswith('#')):
                        message['attachments'].append({'kind': 'file_reference', 'uri': uri, 'available': None, 'fetched': False})
                if node.tag in {'img', 'video', 'audio', 'source'} and node.attrs.get('src'):
                    message['attachments'].append({'kind': node.tag, 'uri': node.attrs['src'], 'available': None, 'fetched': False})
            if not fallback:
                for section in sections[2:]:
                    projected = text(section)
                    if projected:
                        message['link_previews'].append(projected)
            reactions = [text(n) for n in content.walk() if n.has_class('_a6-q')]
            message['reactions'] = [{'original_text': value, 'attribution': 'unparsed_export_reaction'} for value in reactions]
            if message['link_previews']:
                message['contamination_flags'].append('separate_link_preview_preserved')
        message['links'] = list(dict.fromkeys(message['links']))
        if re.search(r'(?i)(?:sent an attachment|unsent a message|changed the|named the group|started a call|missed.*call)', body):
            message['classification'] = 'possible_platform_system_event'
            message['contamination_flags'].append('possible_platform_system_event')
        if any(n.tag in {'script', 'iframe', 'object'} or any(k.startswith('on') for k in n.attrs) for n in block.walk()):
            message['contamination_flags'].append('active_html_retained_raw_only')
        messages.append(message)
    warnings = ['HTML message times have no independently established timezone; export-generation offset is not applied to message dates.']
    if parser.repairs or len(parser.stack) > 1:
        warnings.append('Malformed HTML nesting recovered by bounded tree parser; review projections against original bytes.')
    return title, messages, metadata, {'encoding': encoding, 'parser_repairs': parser.repairs, 'warnings': warnings}


def parse_json(raw, source_hash, self_senders):
    try:
        value = json.loads(raw.decode('utf-8-sig'), object_pairs_hook=C._pairs,
                           parse_constant=lambda _: (_ for _ in ()).throw(ValueError('Non-finite number')))
        # Escaped unpaired surrogates may pass json.loads but cannot form a
        # portable UTF-8 derivative. Validate every key/metadata field up front.
        C.canonical_bytes(value)
    except (ValueError, UnicodeError, RecursionError) as exc:
        raise C.ContextError('Malformed UTF-8 Messenger JSON.') from exc
    if not isinstance(value, dict) or not isinstance(value.get('messages'), list) or len(value['messages']) > MAX_MESSAGES:
        raise C.ContextError('Expected a Messenger JSON object with a bounded messages array.')
    title = value.get('title') if isinstance(value.get('title'), str) else 'Untitled supplied Messenger thread'
    messages = []
    for ordinal, item in enumerate(value['messages'], 1):
        if not isinstance(item, dict):
            raise C.ContextError('Malformed Messenger message; no partial import.')
        sender, body = item.get('sender_name', ''), item.get('content', '')
        null_content = body is None
        if null_content:
            body = ''
        if not isinstance(sender, str) or not isinstance(body, str):
            raise C.ContextError('Messenger sender/content must be strings when present.')
        message = base_message(source_hash, ordinal, title, sender, body, self_senders)
        if null_content:
            message['warnings'].append('null_content_projected_as_empty_raw_json_retained')
        stamp = item.get('timestamp_ms'); message['timestamp_original'] = stamp
        message['provider_message_id'] = item.get('message_id') if isinstance(item.get('message_id'), (str, int)) else None
        if type(stamp) is int:
            try:
                dt = datetime.fromtimestamp(stamp / 1000, timezone.utc)
                if not 1970 <= dt.year < 2200:
                    raise ValueError('Outside supported date range')
                message['observed_at'] = dt.isoformat(timespec='milliseconds')
                message['timezone_provenance'] = 'UTC Unix timestamp_ms in supplied JSON'
            except (OverflowError, OSError, ValueError):
                message['warnings'].append('unparsed_timestamp_preserved_verbatim')
        else:
            message['warnings'].append('missing_or_noninteger_timestamp_ms')
        for key in ('photos', 'videos', 'audio_files', 'files', 'gifs'):
            items = item.get(key, [])
            if not isinstance(items, list):
                raise C.ContextError('Attachment collection must be an array.')
            for attachment in items:
                message['attachments'].append({'kind': key, 'source_metadata': attachment, 'fetched': False})
        if 'sticker' in item:
            message['attachments'].append({'kind': 'sticker', 'source_metadata': item['sticker'], 'fetched': False})
        if 'share' in item:
            message['link_previews'].append(item['share'])
            if isinstance(item['share'], dict) and isinstance(item['share'].get('link'), str):
                message['links'].append(item['share']['link'])
            message['contamination_flags'].append('separate_link_preview_preserved')
        message['reactions'] = item.get('reactions', [])
        message['reply_to'] = item.get('reply_to_message_id')
        if item.get('is_unsent') is True:
            message['classification'] = 'platform_system_event'
        # Retain recoverable JSON fields, including future attachment/reply types.
        message['original_message_metadata'] = {k: v for k, v in item.items() if k != 'content'}
        messages.append(message)
    return title, messages, [], {'encoding': 'utf-8-sig', 'warnings': ['Original JSON strings preserved without mojibake repair.']}


def read_export(path, self_senders=()):
    path = Path(path)
    if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_INPUT:
        raise C.ContextError('Use a regular supplied HTML/JSON export up to 64 MB.')
    raw = path.read_bytes(); sha = G.raw_hash(raw)
    if G.file_hash(path) != sha:
        raise C.ContextError('Export changed during read.')
    self_senders = tuple(sorted(set(self_senders)))
    if any(not isinstance(x, str) or not x for x in self_senders):
        raise C.ContextError('Self-sender labels must be nonempty strings.')
    kind = 'json' if raw.lstrip(b'\xef\xbb\xbf \t\r\n').startswith(b'{') else 'html'
    title, messages, metadata, details = (parse_json if kind == 'json' else parse_html)(raw, sha, self_senders)
    for message in messages:
        if len(message['body'].encode('utf-8')) > G.MAX_TEXT_BYTES or '\x00' in message['body']:
            raise C.ContextError('Message exceeds supported body size or contains NUL; original source remains untouched.')
    return {'path': path, 'sha256': sha, 'bytes': raw, 'kind': kind,
            'title': title, 'messages': messages, 'metadata_entries': metadata,
            'self_senders': list(self_senders), 'details': details}


def _batch_id(export):
    return C.digest([VERSION, export['sha256'], export['self_senders']])


def ingest(store, path, self_senders=(), approved=False, expected=None, project=None):
    if not approved:
        raise C.ContextError('Explicit private-import authorization is required.')
    export = read_export(path, self_senders)
    journal = C.read_json(store.journal); data, head = C.load_store(journal)
    expected = expected or head['store_sha256']
    if expected != head['store_sha256']:
        raise C.ContextError('Stale context: re-read before import.')
    if project is not None and project not in {p['id'] for p in data['projects']}:
        raise C.ContextError('Unknown project.')
    key = C.digest([_batch_id(export), project]); report_id = 'MESSENGER.REPORT.' + key
    known = {s['id']: s for s in data['sources']}
    if report_id in known:
        report = json.loads(store.object(known[report_id]['sha256']))
        verify_report(store, report)
        return {**report, 'already_imported': True}
    at = G.now(); records = []; objects = {}
    # A changed attribution configuration cannot silently reclassify an existing
    # witness. Re-import without it or make a separately reviewed derivative.
    for message in export['messages']:
        sid = message['id']; body = message['body'].encode('utf-8')
        if sid in known:
            origin = known[sid].get('origin', {})
            if origin.get('self_sender_labels') != export['self_senders'] or known[sid].get('project_id') != project:
                raise C.ContextError('Existing witness has different attribution/project metadata; no silent overwrite.')
            if store.object(known[sid]['sha256']) != body:
                raise C.ContextError('Existing witness text changed; restore before import.')
            continue
        objects[message['body_sha256']] = body
        source = {'id': sid, 'format': G.SOURCE_FORMAT, 'name': export['title'][:200],
                  'locator': 'continuity-object:sha256:' + message['body_sha256'],
                  'sha256': message['body_sha256'], 'byte_count': len(body),
                  'media_type': 'text/plain; charset=utf-8', 'project_id': project,
                  'visibility': 'private', 'source_kind': 'UNKNOWN',
                  'speaker': 'assistant' if message['authorship'] == 'AI_GENERATED' else 'unknown',
                  'observed_at': message['observed_at'], 'received_at': at,
                  'publication_status': 'unapproved', 'approved_for_publication_at': None,
                  'review_state': 'unreviewed', 'creator_role': 'messenger-adapter',
                  'origin': {'provider': 'messenger', 'adapter': MESSAGE, 'adapter_version': VERSION,
                             'export_sha256': export['sha256'], 'source_ordinal': message['source_ordinal'],
                             'conversation_id': message['conversation_id'], 'sender_label': message['sender'],
                             'self_sender_labels': export['self_senders'],
                             'authorship': message['authorship'], 'style_eligible': False,
                             'timestamp_original': message['timestamp_original'],
                             'datetime_local_unspecified_zone': message['datetime_local_unspecified_zone'],
                             'timezone_provenance': message['timezone_provenance'],
                             'contamination_flags': message['contamination_flags'], 'report_id': report_id},
                  'verification': 'Historical export text projection. Attribution, truth and current validity unverified; raw bytes and import report retain provenance. No training/publication permission.'}
        records.append(source)
    report = {'format': REPORT, 'adapter_version': VERSION, 'batch_id': key,
              'report_id': report_id, 'source_file_sha256': export['sha256'],
              'original_filename': export['path'].name, 'source_format': export['kind'],
              'imported_at': at, 'thread_title': export['title'], 'self_senders': export['self_senders'],
              'project_id': project, 'messages': export['messages'],
              'metadata_entries': export['metadata_entries'], 'details': export['details'],
              'counts': {'message_entries': len(export['messages']),
                         'archive_metadata_entries': len(export['metadata_entries']),
                         'sender_labels': dict(Counter(m['sender'] for m in export['messages'])),
                         'authorship': dict(Counter(m['authorship'] for m in export['messages'])),
                         'style_approved': 0},
              'privacy': 'PRIVATE_VAULT', 'publication_approved': False,
              'parent_journal_sha256': head['store_sha256'],
              'security': 'Objects, journal and backup are plaintext files protected by owner-only permissions. Use an encrypted disk for encryption at rest.',
              'scope': 'Only supplied file is measured. Archive labels do not authenticate correspondents. Repeated URLs are not recovered media. No external fetch, model transfer, training or canonical editing performed.'}
    report_raw = C.canonical_bytes(report); report_sha = G.raw_hash(report_raw)
    raw_id = 'MESSENGER.OBJECT.' + export['sha256']
    if raw_id not in known:
        records.append({'id': raw_id, 'format': ORIGINAL, 'name': export['path'].name,
                        'locator': 'continuity-object:sha256:' + export['sha256'],
                        'sha256': export['sha256'], 'byte_count': len(export['bytes']),
                        'visibility': 'private', 'source_kind': 'SOURCE_FACT',
                        'authority_scope': 'Exact supplied bytes only, not truth of embedded claims',
                        'publication_status': 'unapproved', 'received_at': at})
    records.append({'id': report_id, 'format': REPORT, 'name': 'Messenger source-preserving import receipt',
                    'locator': 'continuity-object:sha256:' + report_sha, 'sha256': report_sha,
                    'byte_count': len(report_raw), 'visibility': 'private', 'source_kind': 'UNKNOWN',
                    'authority_scope': 'Deterministic adapter projections and import coverage only',
                    'publication_status': 'unapproved', 'received_at': at})
    proposal = {'id': 'MESSENGER.IMPORT.' + key, 'at': at, 'actor': 'owner',
                'note': 'Registered exact Messenger original and unreviewed private witnesses; no present-state, publication or authorship approval inferred.',
                'evidence_grade': 'C', 'source_refs': [report_id, raw_id],
                'source_records': records, 'updates': [], 'additions': []}
    candidate, _ = C.append(journal, proposal, expected, True)
    if len(json.dumps(candidate, ensure_ascii=False, indent=2).encode()) + 1 > C.MAX_BYTES:
        raise C.ContextError('Import would exceed existing 32 MB journal; no partial commit. Use another scoped archive or explicit migration.')
    store.put_file(export['path'], expected=export['sha256'], maximum=MAX_INPUT)
    for body in objects.values():
        store.put_object(body)
    store.put_object(report_raw)
    C.apply_file(store.journal, proposal, expected, True)
    verify_report(store, report)
    return report


def verify_report(store, report):
    raw = store.object(report['source_file_sha256'])
    parsed = (parse_json if report['source_format'] == 'json' else parse_html)(raw, report['source_file_sha256'], report['self_senders'])
    if parsed[1] != report['messages'] or parsed[2] != report['metadata_entries']:
        raise C.ContextError('Original-to-derivative round-trip mismatch.')
    sources = {s['id']: s for s in store.state()[0]['sources']}
    for message in report['messages']:
        source = sources.get(message['id'])
        if source is None or source.get('sha256') != message['body_sha256'] or store.object(source['sha256']).decode('utf-8') != message['body']:
            raise C.ContextError('Message witness missing or changed.')
    return {'verified': True, 'messages': len(report['messages']), 'original_sha256': report['source_file_sha256']}


def reports(store):
    return [json.loads(store.object(s['sha256'])) for s in store.state()[0]['sources'] if s.get('format') == REPORT]


def export_jsonl(store):
    """Deterministic exact derivative rows. Contains PRIVATE text; never public."""
    by_id = {}
    for report in reports(store):
        verify_report(store, report)
        for row in report['messages']:
            if row['id'] in by_id and by_id[row['id']] != row:
                raise C.ContextError('Conflicting derivative rows.')
            by_id[row['id']] = row
    ordered = sorted(by_id.values(), key=lambda x: (x['source_file_sha256'], x['source_ordinal']))
    return b''.join(C.canonical_bytes(row) + b'\n' for row in ordered)


def lineage(store, sid, principal):
    source = store.source(sid, principal)['source']
    origin = source.get('origin', {})
    if origin.get('adapter') != MESSAGE:
        raise C.ContextError('Not a Messenger witness.')
    report_source = store.source(origin['report_id'], principal, False)['source']
    report = json.loads(store.object(report_source['sha256']))
    message = next((m for m in report['messages'] if m['id'] == sid), None)
    if message is None:
        raise C.ContextError('Receipt omits message witness.')
    verify_report(store, report)
    return {'message': message, 'source_record': source, 'report_sha256': report_source['sha256'],
            'original_sha256': report['source_file_sha256'],
            'original_locator': 'continuity-object:sha256:' + report['source_file_sha256'],
            'trust': 'untrusted-source-data', 'current_validity': 'historical-only-unverified',
            'publication_approved': False}


def rollback_latest(store, batch_id, expected, approved=False):
    """Remove only the latest Messenger import from active journal, preserving
    exact pre/post journals and immutable objects. Rejects intervening writes.
    """
    if not approved:
        raise C.ContextError('Explicit rollback authorization required.')
    with C.locked(store.journal):
        journal = C.read_json(store.journal); _, head = C.load_store(journal)
        if expected != head['store_sha256'] or not journal['events']:
            raise C.ContextError('Stale or empty journal; rollback refused.')
        event = journal['events'][-1]
        if event['proposal']['id'] != 'MESSENGER.IMPORT.' + batch_id:
            raise C.ContextError('Only latest import can be rolled back; intervening writes require explicit reconciliation.')
        history = G.private_directory(store.root / 'history')
        before = C.canonical_bytes(journal)
        target = history / ('before-messenger-rollback-' + head['store_sha256'] + '.json')
        if target.exists() and (target.is_symlink() or target.read_bytes() != before):
            raise C.ContextError('Rollback history destination differs; preserve and reconcile it first.')
        if not target.exists():
            C.atomic_write(target, before, replace=False)
        journal['events'].pop(); C.load_store(journal)
        C.json_write(store.journal, journal)
        if store.index.exists():
            store.index.unlink()
    return {'rolled_back': batch_id, 'objects_retained': True, 'history_journal_sha256': head['store_sha256'], 'context': store.state()[1]}


