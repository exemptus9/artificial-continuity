"""Offline Messenger witnesses in Continuity's existing private journal/object store.

Python standard library only. Original bytes control every projection. HTML is
parsed as inert data, never rendered, fetched or executed. A matching sender is
an export attribution, not proof of authorship or permission to train/publish.
"""
